#!/usr/bin/env python3
"""Generate the Machado (2009) CVD matrices and simulation test expectations from DaltonLens.

    python3 -m venv .venv && .venv/bin/pip install daltonlens numpy
    .venv/bin/python tools/gen_machado.py

Writes crates/color-core/src/machado_matrices.rs and
crates/color-core/tests/fixtures/machado_reference.json.
"""

import json
from pathlib import Path

import numpy as np
from daltonlens import simulate

ROOT = Path(__file__).resolve().parent.parent
DEFICIENCIES = {
    "PROTAN": simulate.Deficiency.PROTAN,
    "DEUTAN": simulate.Deficiency.DEUTAN,
    "TRITAN": simulate.Deficiency.TRITAN,
}
HEXES = ["#FF0000", "#00FF00", "#0000FF", "#008000", "#87CEEB", "#FFA500", "#800080", "#808080", "#FFFFFF", "#000000", "#D2691E", "#2E8B57"]


def write_matrices():
    lines = [
        "// Generated by tools/gen_machado.py from DaltonLens (machado_2009_matrices).",
        "// Machado, Oliveira & Fernandes (2009), severity steps 0.0, 0.1, ..., 1.0; linear RGB.",
        "",
    ]
    for name, d in DEFICIENCIES.items():
        mats = simulate.machado_2009_matrices[d]  # {0: m0.0, 1: m0.1, ..., 10: m1.0}
        assert sorted(mats) == list(range(11))
        lines.append(f"pub const {name}: [[[f64; 3]; 3]; 11] = [")
        for step in range(11):
            m = np.asarray(mats[step])
            rows = ", ".join("[" + ", ".join(f"{v:.6f}" for v in row) + "]" for row in m)
            lines.append(f"    [{rows}],")
        lines.append("];")
        lines.append("")
    out = ROOT / "crates/color-core/src/machado_matrices.rs"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


def write_reference():
    sim = simulate.Simulator_Machado2009()
    rows = []
    for hex_value in HEXES:
        rgb = np.array([[[int(hex_value[i : i + 2], 16) for i in (1, 3, 5)]]], dtype=np.uint8)
        for name, d in DEFICIENCIES.items():
            # Only the published severity steps: DaltonLens' interpolation between steps uses
            # an unscaled weight, so in-between severities are not a valid reference.
            for severity in (0.3, 0.7, 1.0):
                out = sim.simulate_cvd(rgb, d, severity=severity)[0, 0]
                rows.append({"hex": hex_value, "deficiency": name.lower(), "severity": severity,
                             "expected": "#%02X%02X%02X" % tuple(int(v) for v in out)})
    out = ROOT / "crates/color-core/tests/fixtures/machado_reference.json"
    out.write_text(json.dumps({"source": "DaltonLens Simulator_Machado2009", "cases": rows}, indent=1) + "\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(rows)} cases)")


if __name__ == "__main__":
    write_matrices()
    write_reference()
